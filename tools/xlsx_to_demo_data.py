"""Convert the fake test-data workbook into frontend/assets/js/demo/demo-data.js.

Usage:
    python tools/xlsx_to_demo_data.py path/to/RFID_Test_Data.xlsx

Every value is exported as text, matching how the Google Sheet stores it.
"""
import json
import sys
from pathlib import Path

from openpyxl import load_workbook

OUTPUT = Path(__file__).resolve().parent.parent / "frontend" / "assets" / "js" / "demo" / "demo-data.js"
SKIPPED_SHEETS = {"README"}


def sheet_to_records(worksheet):
    rows = list(worksheet.iter_rows(values_only=True))
    if not rows:
        return []
    headers = [str(h).strip() for h in rows[0] if h is not None]
    records = []
    for row in rows[1:]:
        values = ["" if v is None else str(v) for v in row[: len(headers)]]
        if not any(values):
            continue
        records.append(dict(zip(headers, values)))
    return records


def main():
    if len(sys.argv) != 2:
        sys.exit("Usage: python tools/xlsx_to_demo_data.py path/to/RFID_Test_Data.xlsx")
    workbook = load_workbook(sys.argv[1], read_only=True)
    data = {ws.title: sheet_to_records(ws) for ws in workbook.worksheets if ws.title not in SKIPPED_SHEETS}
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by tools/xlsx_to_demo_data.py from the FAKE test-data workbook. Do not edit by hand.\n"
        f"export const DEMO_DATA = Object.freeze({json.dumps(data, indent=1, ensure_ascii=False)});\n",
        encoding="utf-8",
    )
    counts = ", ".join(f"{name}: {len(rows)}" for name, rows in data.items())
    print(f"Wrote {OUTPUT}\n{counts}")


if __name__ == "__main__":
    main()
